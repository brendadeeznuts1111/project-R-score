import { joinPath } from '../path-bun.ts';

export async function stagedProjectPaths(): Promise<readonly string[]> {
  const inventory = Bun.env.KIMI_STAGED_PROJECTS_LS_FILES;
  if (!inventory || !(await Bun.file(inventory).exists())) return [];
  return (await Bun.file(inventory).text()).split('\0').filter(Boolean);
}

export async function scannedPaths(
  root: string,
  glob: string,
  includeStaged: (file: string) => boolean
): Promise<readonly string[]> {
  const files = new Set<string>();
  for await (const file of new Bun.Glob(glob).scan({ cwd: root, onlyFiles: true })) files.add(file);
  for (const file of await stagedProjectPaths()) if (includeStaged(file)) files.add(file);
  return [...files].sort();
}

export async function readRepoText(root: string, file: string): Promise<string> {
  return Bun.file(joinPath(root, file)).text();
}

export async function readRepoJson(root: string, file: string): Promise<unknown> {
  return Bun.file(joinPath(root, file)).json();
}

export async function repoFileExists(file: string): Promise<boolean> {
  return Bun.file(file).exists();
}

export function parseTomlRecord(source: string): Record<string, unknown> {
  return Bun.TOML.parse(source) as Record<string, unknown>;
}
