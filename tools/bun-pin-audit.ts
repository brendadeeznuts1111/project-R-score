type Severity = 'error' | 'warn' | 'info';

interface Finding {
  severity: Severity;
  file: string;
  line?: number;
  kind: string;
  message: string;
}

const argv = Bun.argv.slice(2);
const FIX = argv.includes('--fix');
const JSON_OUT = argv.includes('--json');
const SHOW_ALL = argv.includes('--all');
const pinIdx = argv.indexOf('--pin');
const positionals = argv.filter((a, i) => !a.startsWith('--') && i !== pinIdx + 1);
const ROOT = positionals[0] ?? process.cwd();
const PIN = pinIdx >= 0 ? normalize(argv[pinIdx + 1]) : await resolvePin();
const MAX_PRINT = SHOW_ALL ? Number.POSITIVE_INFINITY : 40;

async function resolvePin(): Promise<string> {
  const pinFile = Bun.file(`${ROOT}/.bun-version`);
  if (await pinFile.exists()) {
    const text = (await pinFile.text()).trim();
    if (/^\d+\.\d+/.test(text)) return normalize(text);
  }
  return normalize(Bun.version);
}

function normalize(v: string): string {
  const m = v.match(/^v?(\d+\.\d+(?:\.\d+)?)/);
  return m ? m[1] : v;
}

function parseSemver(v: string): [number, number, number] | null {
  const m = normalize(v).match(/^(\d+)\.(\d+)(?:\.(\d+))?$/);
  if (!m) return null;
  return [Number(m[1]), Number(m[2]), Number(m[3] ?? 0)];
}

function cmp(a: [number, number, number], b: [number, number, number]): number {
  for (let i = 0; i < 3; i++) {
    if (a[i] !== b[i]) return a[i] - b[i];
  }
  return 0;
}

function olderThanPin(v: string, pin: [number, number, number]): boolean {
  const parsed = parseSemver(v);
  return parsed !== null && cmp(parsed, pin) < 0;
}

function stripSpec(spec: string): string {
  return spec.replace(/^[^0-9]*/, '');
}

function isNumericSpec(spec: string): boolean {
  return /^\^?~?>=?\d+\.\d+/.test(spec.trim());
}

function bumpSpec(spec: string, pin: string): string {
  return spec.replace(/\d+\.\d+(?:\.\d+)?/, pin);
}

const findings: Finding[] = [];
let fixes = 0;

function add(severity: Severity, kind: string, file: string, message: string, line?: number): void {
  findings.push({ severity, kind, file, message, line });
}

function gitLsFiles(): string[] {
  const proc = Bun.spawnSync(['git', 'ls-files', '-z'], { cwd: ROOT });
  if (proc.exitCode !== 0) throw new Error(`git ls-files failed in ${ROOT}`);
  return new TextDecoder()
    .decode(proc.stdout)
    .split('\0')
    .filter(f => f.length > 0 && !f.includes('→'));
}

async function readLines(path: string): Promise<string[]> {
  const text = await Bun.file(`${ROOT}/${path}`).text();
  return text.split('\n');
}

async function rewrite(path: string, lines: string[]): Promise<boolean> {
  const original = await Bun.file(`${ROOT}/${path}`).text();
  const next = lines.join('\n');
  if (next === original || next === original.replace(/\n$/, '')) {
    const normalizedOriginal = original.endsWith('\n') ? original : `${original}\n`;
    if (normalizedOriginal !== `${next}\n`) {
      await Bun.write(`${ROOT}/${path}`, `${next}\n`);
      return true;
    }
    return false;
  }
  await Bun.write(`${ROOT}/${path}`, `${next}\n`);
  return true;
}

async function checkPackageJson(path: string): Promise<void> {
  const raw = await Bun.file(`${ROOT}/${path}`).text();
  let pkg: Record<string, unknown>;
  try {
    pkg = JSON.parse(raw);
  } catch (e) {
    add('error', 'pkg-json', path, `invalid JSON: ${(e as Error).message}`);
    return;
  }

  const pin = parseSemver(PIN);

  const pm = typeof pkg.packageManager === 'string' ? pkg.packageManager : null;
  if (pm?.startsWith('bun@')) {
    const v = pm.slice(4);
    if (parseSemver(v) && pin && olderThanPin(v, PIN)) {
      add(
        'error',
        'pkg-packageManager',
        path,
        `packageManager ${pm} is older than pin ${PIN}`,
        rawLine(raw, '"packageManager"')
      );
    } else if (FIX && parseSemver(v) && !olderThanPin(v, PIN) && normalize(v) !== PIN) {
      add('info', 'pkg-packageManager', path, `packageManager ${pm} differs from pin ${PIN}`);
    }
  }

  const engines = pkg.engines as Record<string, string> | undefined;
  const engineRange = engines?.bun;
  if (typeof engineRange === 'string') {
    let ok: boolean;
    try {
      ok = Bun.semver.satisfies(PIN, engineRange);
    } catch {
      ok = false;
    }
    if (!ok) {
      add(
        'error',
        'pkg-engines',
        path,
        `engines.bun "${engineRange}" excludes pin ${PIN}`,
        rawLine(raw, '"engines"')
      );
    }
  }

  walkDeps(pkg, [], path, pin);
}

type DepNode = Record<string, unknown>;

function walkDeps(
  node: string | string[] | DepNode,
  trail: string[],
  path: string,
  pin: [number, number, number] | null
): void {
  if (typeof node === 'string') return;
  if (Array.isArray(node)) {
    for (const item of node) walkDeps(item, trail, path, pin);
    return;
  }
  for (const [key, value] of Object.entries(node)) {
    if ((key === '@types/bun' || key === 'bun-types') && typeof value === 'string') {
      if (isNumericSpec(value) && pin && olderThanPin(stripSpec(value), pin)) {
        add(
          'error',
          'pkg-types-pin',
          path,
          `${key} "${value}" in ${trail.join('.') || 'root'} predates pin ${PIN}`
        );
      }
      continue;
    }
    walkDeps(value, [...trail, key], path, pin);
  }
}

function rawLine(raw: string, needle: string): number | undefined {
  const idx = raw.indexOf(needle);
  if (idx < 0) return undefined;
  return raw.slice(0, idx).split('\n').length;
}

function applyPackageJsonFixes(path: string): Promise<boolean> {
  return rewriteWithTransform(path, line => {
    let out = line.replace(/("packageManager"\s*:\s*")bun@\d+\.\d+(?:\.\d+)?(")/, `$1bun@${PIN}$2`);
    out = out.replace(
      /("(?:@types\/bun|bun-types)"\s*:\s*")([^"]+)(")/g,
      (_m, pre: string, spec: string, post: string) => {
        if (!isNumericSpec(spec)) return _m;
        if (!olderThanPin(stripSpec(spec), parseSemver(PIN)!)) return _m;
        return `${pre}${bumpSpec(spec, PIN)}${post}`;
      }
    );
    if (/"engines"/.test(out)) return out;
    return out.replace(
      /("bun"\s*:\s*")(>?>=?\^?~?)\d+\.\d+(?:\.\d+)?(")/g,
      (_m, pre: string, op: string, post: string) => {
        return `${pre}${op}${PIN}${post}`;
      }
    );
  });
}

async function rewriteWithTransform(
  path: string,
  transform: (line: string) => string
): Promise<boolean> {
  const lines = await readLines(path);
  let changed = false;
  const next = lines.map(line => {
    const t = transform(line);
    if (t !== line) changed = true;
    return t;
  });
  if (!changed) return false;
  await Bun.write(`${ROOT}/${path}`, `${next.join('\n')}\n`);
  return true;
}

async function checkBunfig(path: string): Promise<void> {
  try {
    Bun.TOML.parse(await Bun.file(`${ROOT}/${path}`).text());
  } catch (e) {
    add(
      'error',
      'bunfig-strict-toml',
      path,
      `fails Bun 1.4 strict TOML: ${(e as Error).message.split('\n')[0]}`
    );
  }
}

async function checkLockfile(path: string): Promise<void> {
  const head = (await Bun.file(`${ROOT}/${path}`).text()).slice(0, 600);
  const lv = head.match(/"lockfileVersion"\s*:\s*(\d+)/);
  const cv = head.match(/"configVersion"\s*:\s*(\d+)/);
  const lvNum = lv ? Number(lv[1]) : null;
  const cvNum = cv ? Number(cv[1]) : null;
  if (lvNum === null) {
    add('warn', 'lock-version', path, 'no lockfileVersion found');
  } else if (lvNum >= 3) {
    add('error', 'lock-version', path, `lockfileVersion ${lvNum} unreadable by older Bun`);
  } else if (lvNum < 2) {
    add('warn', 'lock-version', path, `lockfileVersion ${lvNum}; 1.4 writes 2 (still loads)`);
  }
  if (cvNum === null) {
    add('info', 'lock-config', path, 'no configVersion (configVersion 0, hoisted default)');
  }
}

const DOC_PATTERNS: RegExp[] = [
  /\bbun\s+v?(\d+)\.(\d+)(?:\.(\d+))?/gi,
  /\bbun@(\d+)\.(\d+)(?:\.\d+)?/gi,
];

async function checkDocFile(path: string): Promise<void> {
  const lines = await readLines(path);
  const pinTuple = parseSemver(PIN);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.includes('://')) continue;
    for (const pattern of DOC_PATTERNS) {
      pattern.lastIndex = 0;
      let m: RegExpExecArray | null;
      while ((m = pattern.exec(line)) !== null) {
        const version = m[0].match(/(\d+\.\d+(?:\.\d+)?)/)?.[1];
        if (!version || !pinTuple || !olderThanPin(version, pinTuple)) continue;
        add(
          'warn',
          'doc-stale-pointer',
          path,
          `references ${m[0].trim()} (below pin ${PIN})`,
          i + 1
        );
      }
    }
  }
}

const CODE_EXT = /\.(ts|tsx|js|jsx|mjs|cjs)$/;

async function checkCodeFile(path: string): Promise<void> {
  if (path.endsWith('.d.ts')) return;
  if (path === 'tools/bun-pin-audit.ts') return;
  const lines = await readLines(path);
  for (let i = 0; i < lines.length; i++) {
    if (/writeHeader\s*\(/.test(lines[i])) {
      add(
        'error',
        'node26-writeHeader',
        path,
        'res.writeHeader() removed in Node 26 compat; use res.writeHead()',
        i + 1
      );
    }
  }
}

async function checkYamlFile(path: string): Promise<void> {
  const lines = await readLines(path);
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/(bun[-_]version)\s*:\s*["']?v?(\d+)\.(\d+)(?:\.(\d+))?/);
    if (!m) continue;
    const version = `${m[2]}.${m[3]}${m[4] ? `.${m[4]}` : ''}`;
    if (olderThanPin(version, parseSemver(PIN)!)) {
      add('error', 'ci-bun-version', path, `${m[1]} pinned to ${version}, below pin ${PIN}`, i + 1);
      if (FIX) {
        lines[i] = lines[i].replace(/(\d+\.\d+(?:\.\d+)?)/, PIN);
        if (await rewrite(path, lines)) fixes++;
      }
    }
  }
}

async function main(): Promise<number> {
  const pinParsed = parseSemver(PIN);
  if (!pinParsed) throw new Error(`invalid pin: ${PIN}`);
  add('info', 'meta', '.', `auditing ${ROOT} against pin ${PIN}${FIX ? ' (fix mode)' : ''}`);

  const files = gitLsFiles().filter(
    f => !f.startsWith('.bun-cache/') && !f.includes('/.bun-cache/')
  );
  const pkgFiles: string[] = [];
  const bunfigFiles: string[] = [];
  const lockFiles: string[] = [];
  const mdFiles: string[] = [];
  const ymlFiles: string[] = [];
  const codeFiles: string[] = [];

  for (const f of files) {
    const base = f.split('/').pop() ?? '';
    if (base === 'package.json') pkgFiles.push(f);
    else if (base === 'bunfig.toml' || base === '.bunfig.toml') bunfigFiles.push(f);
    else if (base === 'bun.lock') lockFiles.push(f);
    else if (base === '.bun-version') continue;
    else if (base.endsWith('.md')) mdFiles.push(f);
    else if (base.endsWith('.yml') || base.endsWith('.yaml')) ymlFiles.push(f);
    else if (CODE_EXT.test(base)) codeFiles.push(f);
  }

  for (const f of pkgFiles) await checkPackageJson(f);
  for (const f of bunfigFiles) await checkBunfig(f);
  for (const f of lockFiles) await checkLockfile(f);
  for (const f of ymlFiles) await checkYamlFile(f);
  for (const f of codeFiles) await checkCodeFile(f);
  for (const f of mdFiles) await checkDocFile(f);

  if (FIX) {
    for (const f of pkgFiles) {
      if (await applyPackageJsonFixes(f)) fixes++;
    }
    findings.length = 0;
    fixes = 0;
    for (const f of pkgFiles) await checkPackageJson(f);
    for (const f of bunfigFiles) await checkBunfig(f);
    for (const f of lockFiles) await checkLockfile(f);
    for (const f of ymlFiles) await checkYamlFile(f);
    for (const f of codeFiles) await checkCodeFile(f);
    for (const f of mdFiles) await checkDocFile(f);
  }

  const errors = findings.filter(f => f.severity === 'error' && f.kind !== 'meta');
  const warnings = findings.filter(f => f.severity === 'warn');

  if (JSON_OUT) {
    console.log(
      JSON.stringify(
        {
          pin: PIN,
          fixMode: FIX,
          errors,
          warnings,
          totals: { errors: errors.length, warnings: warnings.length },
        },
        null,
        2
      )
    );
  } else {
    const ordered = [...errors, ...warnings, ...findings.filter(f => f.severity === 'info')];
    console.log(`# bun-pin-audit · pin ${PIN} · ${ROOT}`);
    console.log(
      `# ${errors.length} error(s), ${warnings.length} warning(s)${FIX ? `, ${fixes} fix(es) applied` : ''}`
    );
    for (const f of ordered.slice(0, MAX_PRINT)) {
      const loc = f.line ? `:${f.line}` : '';
      console.log(`[${f.severity}] ${f.kind} ${f.file}${loc} — ${f.message}`);
    }
    if (ordered.length > MAX_PRINT) console.log(`… ${ordered.length - MAX_PRINT} more (use --all)`);
  }

  const blocking = findings.filter(f => f.severity === 'error').length;
  return FIX ? (blocking > 0 ? 1 : 0) : blocking > 0 ? 1 : 0;
}

if (import.meta.main) {
  process.exitCode = await main();
}
