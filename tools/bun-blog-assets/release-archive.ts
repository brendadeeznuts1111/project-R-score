// eslint-disable-next-line no-restricted-imports -- Bun has no directory-creation API
import { mkdir } from 'node:fs/promises';
import { dirnamePath, joinPath } from '../../lib/path-bun.ts';
import { REPO_ROOT } from './constants.ts';
import type { Bun14ReleaseSnapshot, ReleaseSnapshotInput } from './release-snapshot.ts';

export type ArchivedBun14Release = Bun14ReleaseSnapshot & {
  archivedAt: string;
  archivePath: string;
  archiveSha256: string;
};

function sha256(bytes: Uint8Array): string {
  return new Bun.CryptoHasher('sha256').update(bytes).digest('hex');
}

export async function writeBun14ReleaseArchive(
  snapshot: Bun14ReleaseSnapshot,
  input: ReleaseSnapshotInput,
  outputRoot = joinPath(REPO_ROOT, 'reports/channel-releases/bun-1.4')
): Promise<ArchivedBun14Release> {
  const archiveName = `${snapshot.snapshotDigest}.tar.gz`;
  const archivePath = joinPath(outputRoot, archiveName);
  await mkdir(dirnamePath(archivePath), { recursive: true });
  if (!(await Bun.file(archivePath).exists())) {
    await Bun.Archive.write(archivePath, input, { compress: 'gzip', level: 9 });
  }
  const archiveBytes = await Bun.file(archivePath).bytes();
  const archived: ArchivedBun14Release = {
    ...snapshot,
    archivedAt: new Date().toISOString(),
    archivePath: archivePath.startsWith(REPO_ROOT)
      ? archivePath.slice(REPO_ROOT.length + 1)
      : archivePath,
    archiveSha256: sha256(archiveBytes),
  };
  await Bun.write(joinPath(outputRoot, 'latest.json'), `${JSON.stringify(archived, null, 2)}\n`);
  return archived;
}

export async function verifyBun14ReleaseArchive(
  archived: ArchivedBun14Release,
  root = REPO_ROOT
): Promise<void> {
  const archivePath = archived.archivePath.startsWith('/')
    ? archived.archivePath
    : joinPath(root, archived.archivePath);
  const bytes = await Bun.file(archivePath).bytes();
  if (sha256(bytes) !== archived.archiveSha256) throw new Error('channel archive SHA-256 mismatch');
  const entries = await new Bun.Archive(bytes).files();
  for (const file of archived.files) {
    const archivedFile = entries.get(file.path);
    if (!archivedFile) throw new Error(`channel archive missing ${file.path}`);
    if (sha256(await archivedFile.bytes()) !== file.sha256) {
      throw new Error(`channel archive content mismatch: ${file.path}`);
    }
  }
}
