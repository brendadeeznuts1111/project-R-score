#!/usr/bin/env bun
// Native Bun theme sync: theme.jsonc -> CSS tokens (replaces fs-based sync).
// Usage: bun tools/theme-sync.ts [--check]

import { CryptoHasher } from "bun";
import { Glob } from "bun";

const ROOT = new URL("..", import.meta.url).pathname;
const THEME_PATH = `${ROOT}public/portal/theme.jsonc`;
const OUT_PATH = `${ROOT}public/portal/theme-sync.generated.css`;
const CHECK = process.argv.includes("--check");

async function main() {
  // 1. Parse theme.jsonc via Bun.file().json()
  const raw = await Bun.file(THEME_PATH).text();
  const theme = Bun.JSONC.parse(raw);
  if (!theme?.dark || !theme?.light) throw new Error("theme.jsonc missing dark/light");

  // 2. Parity check: dark vs light key sets
  const darkKeys = Object.keys(theme.dark).filter((k) => k !== "neutral");
  const lightKeys = Object.keys(theme.light).filter((k) => k !== "neutral");
  for (const k of darkKeys) {
    if (!lightKeys.includes(k)) throw new Error(`parity: light missing "${k}"`);
  }
  for (const k of lightKeys) {
    if (!darkKeys.includes(k)) throw new Error(`parity: dark missing "${k}"`);
  }

  // 3. Alias lint: colors.* values must be var(--...) references
  if (theme.colors) {
    for (const group of Object.values(theme.colors as Record<string, Record<string, string>>)) {
      for (const [k, v] of Object.entries(group)) {
        if (typeof v !== "string" || !/^var\(--/.test(v)) {
          throw new Error(`alias lint: colors.*.${k} must be var(--...), got ${v}`);
        }
      }
    }
  }

  // 4. Contrast validation (WCAG) — userland math
  function hexToRgb(hex: string): [number, number, number] | null {
    const m = hex.match(/^#([0-9a-f]{6})$/i);
    if (!m) return null;
    const n = parseInt(m[1], 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  function luminance([r, g, b]: [number, number, number]): number {
    const [rs, gs, bs] = [r, g, b].map((c) => {
      const s = c / 255;
      return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * rs + 0.7152 * gs + 0.0722 * bs;
  }
  const bg = hexToRgb(theme.dark.bg);
  const text = hexToRgb(theme.dark.text);
  if (bg && text) {
    const l1 = luminance(bg), l2 = luminance(text);
    const ratio = (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
    if (ratio < 4.5) throw new Error(`contrast: bg/text ratio ${ratio.toFixed(2)} < 4.5`);
  }

  // 4. Flatten -> CSS (minimal: dark palette)
  const lines: string[] = [":root {", "  color-scheme: dark;"];
  for (const [k, v] of Object.entries(theme.dark as Record<string, unknown>)) {
    if (k === "neutral") {
      for (const [nk, nv] of Object.entries(v as Record<string, string>)) {
        lines.push(`  --neutral-${nk}: ${nv};`);
      }
    } else {
      const cssKey = k.replace(/([A-Z])/g, "-$1").toLowerCase();
      lines.push(`  --${cssKey}: ${v};`);
    }
  }
  lines.push("}");
  const css = lines.join("\n") + "\n";

  // 5. Drift check via CryptoHasher (sha256)
  const hasher = new CryptoHasher("sha256");
  hasher.update(css);
  const digest = hasher.digest("hex");

  if (CHECK) {
    const existing = await Bun.file(OUT_PATH).text().catch(() => "");
    const existingHasher = new CryptoHasher("sha256");
    existingHasher.update(existing);
    if (existingHasher.digest("hex") !== digest) {
      console.error("drift detected: generated CSS differs from committed file");
      process.exit(1);
    }
    console.log("OK: no drift");
    return;
  }

  // 6. Write via Bun.write
  await Bun.write(OUT_PATH, css);
  // 5. Typed bindings generation
  const bindingsPath = `${ROOT}public/portal/theme.generated.ts`;
  const subsystems = Object.keys(theme.identity?.subsystem ?? {});
  const venues = Object.keys(theme.identity?.venue ?? {});
  const bindings = `// Auto-generated by tools/theme-sync.ts — do not edit.
export type Subsystem = ${subsystems.map((s) => JSON.stringify(s)).join(" | ") || "string"};
export type Venue = ${venues.map((s) => JSON.stringify(s)).join(" | ") || "string"};
export type Tone = "ok" | "warn" | "old" | "bad" | "info" | "skip";
`;
  await Bun.write(bindingsPath, bindings);
  console.log(`wrote ${bindingsPath}`);

  console.log(`wrote ${OUT_PATH} (sha256 ${digest.slice(0, 12)})`);
}

// 7. Optional: consumer discovery via Glob
async function findConsumers() {
  const glob = new Glob("public/portal/**/*.js");
  const consumers: string[] = [];
  for await (const f of glob.scan({ cwd: ROOT })) {
    const text = await Bun.file(`${ROOT}${f}`).text();
    if (text.includes("var(--")) consumers.push(f);
  }
  return consumers;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
