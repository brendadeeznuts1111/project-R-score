// Emit typed bindings (unions) from theme identity.
export function emitTs(theme: any): string {
  const subsystems = Object.keys(theme.identity?.subsystem ?? {});
  const venues = Object.keys(theme.identity?.venue ?? {});
  return `// Auto-generated by scripts/theme — do not edit.
export type Subsystem = ${subsystems.map((s: string) => JSON.stringify(s)).join(' | ') || 'string'};
export type Venue = ${venues.map((s: string) => JSON.stringify(s)).join(' | ') || 'string'};
export type Tone = "ok" | "warn" | "old" | "bad" | "info" | "skip";
`;
}
