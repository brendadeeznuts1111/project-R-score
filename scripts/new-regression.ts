/**
 * Scaffold a Bun release regression probe file under tests/regression/.
 *
 * Usage (repo root):
 *   bun scripts/new-regression.ts 1.3.15
 *   bun scripts/new-regression.ts --from-current
 *   bun scripts/new-regression.ts 1.3.15 --dry-run
 *   bun run regression:new -- 1.3.15
 *
 * @see tests/regression/README.md
 * @see https://bun.com/blog
 */
import { joinPath } from '../lib/path-bun.ts';

type Args = {
  version: string | null;
  fromCurrent: boolean;
  dryRun: boolean;
  noTest: boolean;
  force: boolean;
  help: boolean;
};

function usage(): string {
  return `Usage: bun scripts/new-regression.ts <bun-version> [flags]
       bun scripts/new-regression.ts --from-current [flags]

Flags:
  --from-current   Use live Bun.version (ignores positional version)
  --dry-run        Print target path + template; do not write
  --no-test        Skip the post-scaffold bun test sanity check
  --force          Overwrite an existing tests/regression/bun-<ver>.test.ts
  -h, --help       Show this help

Example:
  bun scripts/new-regression.ts 1.3.15
`;
}

function parseArgs(argv: string[]): Args {
  const out: Args = {
    version: null,
    fromCurrent: false,
    dryRun: false,
    noTest: false,
    force: false,
    help: false,
  };
  for (const arg of argv) {
    if (arg === '-h' || arg === '--help') out.help = true;
    else if (arg === '--from-current') out.fromCurrent = true;
    else if (arg === '--dry-run') out.dryRun = true;
    else if (arg === '--no-test') out.noTest = true;
    else if (arg === '--force') out.force = true;
    else if (arg.startsWith('-')) {
      throw new Error(`Unknown flag: ${arg}\n${usage()}`);
    } else if (out.version === null) {
      out.version = arg;
    } else {
      throw new Error(`Unexpected argument: ${arg}\n${usage()}`);
    }
  }
  return out;
}

function isSemver(v: string): boolean {
  return /^\d+\.\d+\.\d+$/.test(v);
}

