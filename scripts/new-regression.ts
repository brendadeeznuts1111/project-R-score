async function updateReadme(readmePath: string, version: string, dryRun: boolean): Promise<void> {
  const readme = Bun.file(readmePath);
  if (!(await readme.exists())) {
    console.warn(`⚠️  ${readmePath} missing — skip README update`);
    return;
  }

  let text = await readme.text();
  const linkLine = `| \`${version}\` | [\`bun-${version}.test.ts\`](./bun-${version}.test.ts) | [blog](https://bun.com/blog/bun-v${version}) |`;
  if (text.includes(`bun-${version}.test.ts`)) {
    console.log(`ℹ️  README already lists bun-${version}.test.ts`);
    return;
  }

  const marker = '<!-- regression-release-table -->';
  if (text.includes(marker)) {
    text = text.replace(marker, `${marker}\n${linkLine}`);
  } else if (/\| Version \| File \| Blog \|/.test(text)) {
    text = text.replace(
      /(\| Version \| File \| Blog \|\n\|[- ]+\|[- ]+\|[- ]+\|)/,
      `$1\n${linkLine}`
    );
  } else {
    text += `\n## Releases\n\n| Version | File | Blog |\n| ------- | ---- | ---- |\n${linkLine}\n`;
  }

  if (dryRun) {
    console.log(`DRY-RUN would update README with:\n${linkLine}`);
    return;
  }
  await Bun.write(readmePath, text);
  console.log(`✅ Updated ${readmePath}`);
}

async function main(): Promise<number> {
  let args: Args;
  try {
    args = parseArgs(Bun.argv.slice(2));
  } catch (e) {
    console.error(String((e as Error).message));
    return 2;
  }

  if (args.help) {
    console.log(usage());
    return 0;
  }

  const version = args.fromCurrent ? Bun.version : args.version;
  if (!version) {
    console.error(usage());
    return 2;
  }
  if (!isSemver(version)) {
    console.error(`Error: version must be semver X.Y.Z (got ${JSON.stringify(version)})`);
    return 2;
  }

  const root = joinPath(import.meta.dir, '..');
  const targetRel = `tests/regression/bun-${version}.test.ts`;
  const targetAbs = joinPath(root, targetRel);
  const readmeAbs = joinPath(root, 'tests/regression/README.md');
  const generatedOn = new Date().toISOString().slice(0, 10);
  const source = scaffoldSource(version, generatedOn, Bun.version);

  const targetExists = await Bun.file(targetAbs).exists();
  if (targetExists && !args.force && !args.dryRun) {
    console.error(`Error: ${targetRel} already exists (pass --force to overwrite)`);
    return 1;
  }

  if (args.dryRun) {
    console.log(`DRY-RUN target: ${targetRel}`);
    console.log('---');
    console.log(source);
    await updateReadme(readmeAbs, version, true);
    return 0;
  }

  await Bun.write(targetAbs, source);
  console.log(`✅ Created ${targetRel}`);
  await updateReadme(readmeAbs, version, false);

  if (!args.noTest) {
    console.log(`Running sanity check: bun test ${targetRel}`);
    const proc = Bun.spawn([process.execPath, 'test', targetRel], {
      cwd: root,
      stdout: 'inherit',
      stderr: 'inherit',
    });
    const code = await proc.exited;
    if (code !== 0) {
      console.error(`⚠️  bun test exited ${code} — scaffold may need a tweak`);
      return code;
    }
  }

  console.log(`🎉 Done. Open ${targetRel} and replace TODOs with blog probes.`);
  console.log(`   Blog: https://bun.com/blog/bun-v${version}`);
  return 0;
}

if (import.meta.main) {
  process.exit(await main());
}
