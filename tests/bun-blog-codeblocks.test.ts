describe('bun-blog-codeblocks extract', () => {
  test('counts CodeBlock and skips CodeBlockTab', async () => {
    const html = await Bun.file(FIXTURE).text();
    const result = extractCodeBlocks(html);
    expect(result.codeBlockCount).toBe(2);
    expect(result.codeBlockTabCount).toBe(1);
    expect(result.blocks).toHaveLength(2);
    expect(result.blocks[0]?.section).toBe('files in Bun.build');
    expect(result.blocks[1]?.section).toBe('S3 Requester Pays Support');
    expect(result.blocks[0]?.code).toContain('Bun.build');
    expect(result.blocks[1]?.code).toContain('requestPayer: true');
    expect(result.classPattern).toBe('CodeBlock*');
    expect(result.classStatuses).toEqual([
      { className: 'CodeBlock', status: 'parsed', statusLabel: 'parsed', count: 2 },
      {
        className: 'CodeBlockTab',
        status: 'skipped',
        statusLabel: 'skipped · tab container',
        count: 1,
      },
    ]);
    expect(result.blocks.every(block => block.statusLabel === 'parsed')).toBe(true);
  });

  test('accepts CodeBlock as one token in Bun blog class lists', () => {
    const html = `<h2>Current Bun markup</h2>
      <div class="CodeBlock group/code"><div class="relative CodeBlockShell">
        <pre><code><span class="line"><span>const value = 1;</span></span></code></pre>
      </div></div>`;
    const result = extractCodeBlocks(html);
    expect(result.codeBlockCount).toBe(1);
    expect(result.blocks[0]?.section).toBe('Current Bun markup');
    expect(result.blocks[0]?.code).toBe('const value = 1;');
    expect(result.blocks[0]?.classNames).toEqual(['CodeBlock', 'group/code']);
    expect(result.classStatuses).toContainEqual({
      className: 'CodeBlockShell',
      status: 'scoped',
      statusLabel: 'scoped · supporting class',
      count: 1,
    });
  });

  test('Bun.Glob class matching accepts single-quoted markup without substring leakage', () => {
    const html = `<h2>Quoted</h2>
      <div class='NotCodeBlock CodeBlock group/code'><pre><code>const ok = true;</code></pre></div>
      <div class='CodeBlockToolbar'></div>`;
    const result = extractCodeBlocks(html);
    expect(result.blocks).toHaveLength(1);
    expect(result.classStatuses.map(row => row.className)).toEqual([
      'CodeBlock',
      'CodeBlockToolbar',
    ]);
  });

  test('BunFile input and Bun.inspect.table property contracts stay explicit', async () => {
    const file = Bun.file(FIXTURE);
    expectTypeOf(file).toEqualTypeOf<Bun.BunFile>();
    const result = await extractCodeBlocksFromFile(file);
    expect(result.codeBlockCount).toBe(2);

    expect(CODE_BLOCK_TABLE_PROPERTIES).toEqual([
      '#',
      'status',
      'class',
      'section',
      'lines',
      'preview',
    ]);
    expect(CODE_BLOCK_CLASS_TABLE_PROPERTIES).toEqual(['class', 'status', 'count']);
    const table = Bun.inspect.table(
      codeBlockClassRows(result.classStatuses),
      [...CODE_BLOCK_CLASS_TABLE_PROPERTIES],
      { colors: false }
    );
    expect(table).toContain('skipped · tab container');
    expect(table).not.toContain('className');
  });

  test('previewLine prefers first non-comment line', () => {
    const preview = previewLine('// comment\nimport { s3 } from "bun";\ns3.file("x");');
    expect(preview).toBe('import { s3 } from "bun";');
  });

  test('parseBlogVersion from url / filename / semver', () => {
    expect(parseBlogVersion('https://bun.com/blog/bun-v1.3.6')).toBe('1.3.6');
    expect(parseBlogVersion('/tmp/bun-v1.3.6.html')).toBe('1.3.6');
    expect(parseBlogVersion('1.3.6')).toBe('1.3.6');
    expect(parseBlogVersion('nope')).toBeNull();
  });

  test('blogUrlForVersion uses bunBlog canonical shape', () => {
    const url = blogUrlForVersion('1.3.6');
    expect(url).toBe(bunBlog('bun-v1.3.6'));
    expect(BunBlogPattern.test(url)).toBe(true);
  });

  test('filterBlocks --section and --grep', async () => {
    const html = await Bun.file(FIXTURE).text();
    const { blocks } = extractCodeBlocks(html);
    expect(filterBlocks(blocks, { section: 2 })).toHaveLength(1);
    expect(filterBlocks(blocks, { section: 2 })[0]?.index).toBe(2);
    expect(filterBlocks(blocks, { grep: 'requestPayer' })).toHaveLength(1);
    expect(filterBlocks(blocks, { grep: 'files in Bun' })).toHaveLength(1);
    expect(filterBlocks(blocks, { all: true })).toHaveLength(2);
    expect(filterBlocks(blocks, {})).toHaveLength(0);
  });
});

describe('bun-blog-codeblocks CLI', () => {
  test('resolves one typed mode from the new flag and compatibility aliases', () => {
    expect(resolveCodeBlockMode({})).toEqual({ mode: 'index', join: false, derived: false });
    expect(resolveCodeBlockMode({ mode: 'all' })).toEqual({
      mode: 'all',
      join: true,
      derived: true,
    });
    expect(resolveCodeBlockMode({ join: true })).toEqual({
      mode: 'join',
      join: true,
      derived: false,
    });
    expect(resolveCodeBlockMode({ join: true, derivedTable: true }).mode).toBe('all');
    expect(() => resolveCodeBlockMode({ mode: 'legacy' })).toThrow(/index\|join\|derived\|all/);
    expect(() => resolveCodeBlockMode({ mode: 'index', join: true })).toThrow(/Do not combine/);
  });

  test('runCli on fixture prints index and writes artifacts', async () => {
    const outDir = resolvePath(Bun.env.TMPDIR ?? '/tmp', `fw-blog-cb-${Bun.randomUUIDv7()}`);
    const code = await runCli([
      FIXTURE,
      '--url',
      'https://bun.com/blog/bun-v9.9.9',
      '--out-dir',
      outDir,
    ]);
    expect(code).toBe(0);
    const jsonPath = resolvePath(outDir, 'bun-v9.9.9-CodeBlock.json');
    expect(await Bun.file(jsonPath).exists()).toBe(true);
    const inv = await Bun.file(jsonPath).json();
    expect(inv.count).toBe(2);
    expect(inv.version).toBe('9.9.9');
    expect(inv.guideKey).toBe('blog/bun-v9.9.9');
    expect(inv.classPattern).toBe('CodeBlock*');
    expect(inv.classStatuses).toHaveLength(2);
    expect(inv.blocks[0]?.statusLabel).toBe('parsed');
    const markdown = await Bun.file(
      resolvePath(outDir, 'bun-v9.9.9-CodeBlock.md')
    ).text();
    expect(markdown).toContain('Class pattern: `CodeBlock*` via `Bun.Glob.match()`');
    expect(markdown).toContain('| `CodeBlockTab` | skipped · tab container | 1 |');
    expect(markdown).toContain('Status: **parsed** · Class: `CodeBlock`');
  });

  test('runCli --mode=all combines token join and derived sidecar', async () => {
    const outDir = resolvePath(Bun.env.TMPDIR ?? '/tmp', `fw-blog-cb-join-${Bun.randomUUIDv7()}`);
    const code = await runCli([
      FIXTURE,
      '--url',
      'https://bun.com/blog/bun-v9.9.9',
      '--out-dir',
      outDir,
      '--mode=all',
    ]);
    expect(code).toBe(0);
    const inv = await Bun.file(resolvePath(outDir, 'bun-v9.9.9-CodeBlock.json')).json();
    expect(inv.mode).toBe('all');
    expect(inv.blocks[0]?.matchedTokens).toContain('Bun.build');
    expect(
      await Bun.file(resolvePath(outDir, 'bun-v9.9.9-CodeBlock-DerivedApi.json')).exists()
    ).toBe(true);
  });

  test('missing HTML exits non-zero with curl hint', () => {
    const missing = resolvePath(
      Bun.env.TMPDIR ?? '/tmp',
      `bun-v0.0.0-missing-${Bun.randomUUIDv7()}.html`
    );
    const result = Bun.spawnSync({
      cmd: [
        'bun',
        TOOL,
        missing,
        '--url',
        'https://bun.com/blog/bun-v0.0.0',
        '--offline',
      ],
      stdout: 'pipe',
      stderr: 'pipe',
    });
    expect(result.exitCode).not.toBe(0);
    const err = result.stderr.toString();
    expect(err).toContain('curl -fsSL');
    expect(err).toContain(missing);
  });
});

describe('bun-blog-codeblocks join and derived modes', () => {
  test('maps Bun.build and S3 blocks to catalog names', async () => {
    const html = await Bun.file(FIXTURE).text();
    const { blocks } = extractCodeBlocks(html);
    const joined = matchBlocksToTokens(blocks, {
      version: '9.9.9',
      postUrl: bunBlog('bun-v9.9.9'),
      tokenIndex: new Map([
        ['bun.build', 'Bun.build'],
        ['bun.file', 'Bun.file'],
      ]),
      scrapeAliases: {},
    });
    const build = joined.find(entry => entry.name === 'Bun.build');
    expect(build?.examples[0]?.blockIndex).toBe(1);
    expect(build?.examples[0]?.guideKey).toBe('blog/bun-v9.9.9');
  });

  test('archive fixture joins Bun.Archive, Bun.file, and Bun.write', async () => {
    const html = await Bun.file(ARCHIVE_FIXTURE).text();
    const [tokenIndex, scrapeAliases] = await Promise.all([
      buildTokenIndex(),
      loadScrapeAliases(),
    ]);
    const joined = matchBlocksToTokens(extractCodeBlocks(html).blocks, {
      version: '1.3.6',
      postUrl: bunBlog('bun-v1.3.6'),
      tokenIndex,
      scrapeAliases,
    });
    const names = joined.map(entry => entry.name);
    expect(names).toContain('Bun.Archive');
    expect(names).toContain('Bun.write');
    const archive = joined.find(entry => entry.name === 'Bun.Archive');
    expect(archive?.examples).toHaveLength(3);
    expect(archive?.examples[0]?.kind).toBe('ship');
  });

  test('derived mode splits multi-concern blocks into non-SSOT rows', async () => {
    const html = await Bun.file(ARCHIVE_FIXTURE).text();
    const main = extractCodeBlocks(html).blocks[0]!;
    const [tokenIndex, scrapeAliases] = await Promise.all([
      buildTokenIndex(),
      loadScrapeAliases(),
    ]);
    const rows = buildDerivedApiRows([main], {
      version: '1.3.6',
      tokenIndex,
      scrapeAliases,
    });
    expect(rows.length).toBeGreaterThanOrEqual(5);
    expect(rows.every(row => row.catalogToken === 'Bun.Archive')).toBe(true);
    expect(rows.some(row => row.preview.includes('archive.blob'))).toBe(true);
    expect(rows.every(row => row.source === 'blog-codeblock')).toBe(true);
  });
});
